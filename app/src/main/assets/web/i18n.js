const DICTS = { ru: RU, en: EN };
let current = "ru";

/** Choose a default locale: English only for an explicit en-* browser. */
export function detectLocale() {
  const stored = safeGet("jarvis.lang");
  if (stored === "ru" || stored === "en") return stored;
  const nav = (navigator.language || "ru").toLowerCase();
  return nav.startsWith("en") ? "en" : "ru";
}

export function setLocale(locale) {
  current = locale === "en" ? "en" : "ru";
  safeSet("jarvis.lang", current);
  document.documentElement.lang = current;
}

export function getLocale() {
  return current;
}

/**
 * Translate [key] (dot path) and interpolate `{placeholders}`.
 * Falls back ru → key.
 */
export function t(key, params) {
  const inCurrent = lookup(DICTS[current], key);
  const inRu = lookup(RU, key);
  let value = inCurrent != null ? inCurrent : inRu != null ? inRu : key;
  if (typeof value !== "string") value = String(value);
  if (params) {
    value = value.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m
    );
  }
  return value;
}

/** Human label for an apply-policy token; unknown tokens degrade honestly. */
export function policyBadge(policy) {
  const p = String(policy || "").toUpperCase();
  if (p === "SERVICE_RESTART") return { cls: "badge--service", text: t("policy.badgeService") };
  if (p === "APP_RESTART") return { cls: "badge--app", text: t("policy.badgeApp") };
  if (p === "LIVE") return { cls: "badge--live", text: t("policy.badgeLive") };
  return { cls: "badge--muted", text: String(policy || t("common.unknown")) };
}

export function policyLabel(policy) {
  const p = String(policy || "").toUpperCase();
  if (p === "SERVICE_RESTART") return t("policy.SERVICE_RESTART");
  if (p === "APP_RESTART") return t("policy.APP_RESTART");
  if (p === "LIVE") return t("policy.LIVE");
  return String(policy || t("common.unknown"));
}

function lookup(dict, key) {
  if (!dict) return null;
  let node = dict;
  for (const part of String(key).split(".")) {
    if (node == null || typeof node !== "object") return null;
    node = node[part];
  }
  return typeof node === "string" ? node : null;
}

function safeGet(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}
function safeSet(key, value) {
  try { localStorage.setItem(key, value); } catch { /* storage may be unavailable */ }
}
